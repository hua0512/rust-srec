#[cfg(test)]
mod tests {
    use std::path::Path;

    const REGENERATE: &str = "UPDATE_GENERATED_PROTOS=1 cargo nextest run --locked -p platforms-parser --lib -E 'test(generated_protos)'";

    /// The committed protobuf modules must match what `proto/` generates, so a
    /// schema edit cannot ship without its code. Setting
    /// `UPDATE_GENERATED_PROTOS` rewrites the committed files instead.
    #[test]
    fn generated_protos_are_current() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"));
        let schemas = protox::compile(["douyin.proto", "tiktok.proto"], [root.join("proto")])
            .expect("compile proto schemas");
        let requests = schemas
            .file
            .into_iter()
            .map(|file| {
                let module = prost_build::Module::from_protobuf_package_name(file.package());
                (module, file)
            })
            .collect();
        // Common metadata occurs in chat messages, but its optional room embeds a
        // large response tree. Keeping it inline can make even small chat payloads
        // exhaust Windows thread stacks in unoptimized Prost decode paths.
        let mut generated = prost_build::Config::new()
            .boxed(".douyin.Webcast.Im.Common.room")
            .generate(requests)
            .expect("generate protobuf code");

        let update = std::env::var_os("UPDATE_GENERATED_PROTOS").is_some();
        for (package, path) in [
            ("douyin", "src/extractor/platforms/douyin/douyin_proto.rs"),
            (
                "tiktok.webcast",
                "src/extractor/platforms/tiktok/tiktok_proto.rs",
            ),
        ] {
            let module = prost_build::Module::from_protobuf_package_name(package);
            let code = generated.remove(&module).expect("generated package");
            let code = format!(
                "// @generated by the `generated_protos_are_current` test. Do not edit.\n{code}"
            );
            let path = root.join(path);
            if update {
                std::fs::write(&path, code).expect("write generated protobuf code");
            } else {
                let committed =
                    std::fs::read_to_string(&path).expect("read generated protobuf code");
                assert!(
                    committed == code,
                    "{} is stale; run `{REGENERATE}`",
                    path.display()
                );
            }
        }
        assert!(
            generated.is_empty(),
            "unexpected packages: {:?}",
            generated.keys()
        );
    }
}
