//! Logging routes and the two WebSockets: `/api/logging/stream` (log events)
//! and `/api/downloads/ws` (download and upload status), plus the manual
//! split endpoint that shares the downloads router.
//!
//! Sockets authenticate once at the upgrade and are then revalidated every
//! few seconds, so a revoked or downgraded credential loses an open socket.
//!
//! The log filter is process-global: tests that change it put it back.

