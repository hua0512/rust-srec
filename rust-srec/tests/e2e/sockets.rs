/// A grant downloads once without an Authorization header, and dies with the
/// API key or session that issued it.
#[tokio::test]
async fn log_archive_tokens_download_once_and_die_with_the_credential_that_issued_them() {
    let app = TestApp::start().await;
    let session = app.admin().await.clone();
    let token = session.access.as_str();

    let issued = app
        .get("/api/logging/archive-token", token)
        .await
        .expect_status(StatusCode::OK);
    let grant = issued.body["token"].as_str().expect("archive token");
    assert!(
        grant.len() == 64 && grant.chars().all(|c| matches!(c, '0'..='9' | 'a'..='f')),
        "{grant}"
    );
    let expires_at = chrono::DateTime::parse_from_rfc3339(
        issued.body["expires_at"].as_str().expect("expires_at"),
    )
    .expect("RFC 3339 expires_at");
    let lifetime = expires_at.with_timezone(&chrono::Utc) - chrono::Utc::now();
    assert!(
        (chrono::Duration::minutes(4)..=chrono::Duration::minutes(5)).contains(&lifetime),
        "{lifetime}"
    );

    let query = [("token", grant), ("from", EMPTY_DAY), ("to", EMPTY_DAY)];
    let archive = download_archive(&app, "/api/logging/archive", &query).await;
    assert_eq!(archive.status(), StatusCode::OK);
    assert_eq!(archive.headers()[header::CONTENT_TYPE], "application/zip");
    assert_eq!(
        archive.headers()[header::CONTENT_DISPOSITION],
        "attachment; filename=\"rust-srec-logs-2000-01-01.zip\""
    );
    let bytes = archive.bytes().await.expect("read the archive");
    assert!(bytes.starts_with(b"PK"), "not a ZIP archive");

    assert_grant_refused(&app, grant).await;
    assert_grant_refused(&app, &"0".repeat(64)).await;

    // `/download` is the older name of the same route.
    let grant = archive_token(&app, token).await;
    let alias = download_archive(
        &app,
        "/api/logging/download",
        &[("token", &grant), ("from", EMPTY_DAY), ("to", "2000-01-02")],
    )
    .await;
    assert_eq!(alias.status(), StatusCode::OK);
    assert_eq!(
        alias.headers()[header::CONTENT_DISPOSITION],
        "attachment; filename=\"rust-srec-logs-2000-01-01-to-2000-01-02.zip\""
    );

    let key = app.create_api_key(token, "sockets-full", "full").await;
    let key_grant = archive_token(&app, &key.raw).await;
    app.delete(&format!("/api/auth/api-keys/{}", key.id), token)
        .await
        .expect_status(StatusCode::OK);
    assert_grant_refused(&app, &key_grant).await;

    let session_grant = archive_token(&app, token).await;
    app.post(
        "/api/auth/logout",
        token,
        &json!({ "refresh_token": session.refresh }),
    )
    .await
    .expect_status(StatusCode::OK);
    assert_grant_refused(&app, &session_grant).await;

    app.shutdown().await;
}

#[tokio::test]
async fn logging_routes_sockets_and_manual_split_refuse_read_only_keys_and_bad_credentials() {
    let app = TestApp::start().await;
    let token = app.admin_token().await;
    let read = app
        .create_api_key(&token, "sockets-read_only", "read_only")
        .await;
    let split = "/api/downloads/no-such-attempt/split";

    let filter = current_filter(&app, &token).await;
    let body = json!({ "filter": "rust_srec=trace" });
    for (method, route) in [
        (Method::GET, "/api/logging"),
        (Method::PUT, "/api/logging"),
        (Method::GET, "/api/logging/files"),
        (Method::GET, "/api/logging/entries"),
        (Method::GET, "/api/logging/archive-token"),
        (Method::POST, split),
    ] {
        let body = (method == Method::PUT).then_some(&body);
        app.send(method, route, Some(&read.raw), body)
            .await
            .assert_error(StatusCode::FORBIDDEN, "API_KEY_READ_ONLY");
    }
    assert_eq!(current_filter(&app, &token).await, filter);

    // Sockets refuse before upgrading.
    for route in ["/api/logging/stream", "/api/downloads/ws"] {
        app.refused_socket(&with_query(route, &[("token", &read.raw)]), None)
            .await
            .assert_error(StatusCode::FORBIDDEN, "API_KEY_READ_ONLY");
        app.refused_socket(route, Some(&read.raw))
            .await
            .assert_error(StatusCode::FORBIDDEN, "API_KEY_READ_ONLY");
        app.refused_socket(route, None)
            .await
            .assert_error(StatusCode::UNAUTHORIZED, "UNAUTHORIZED");
        // An Authorization header wins over a valid query token.
        app.refused_socket(&with_query(route, &[("token", &token)]), Some("invalid"))
            .await
            .assert_error(StatusCode::UNAUTHORIZED, "UNAUTHORIZED");
    }

    // Manual split reads credentials from the Authorization header only.
    let query_only = with_query(split, &[("token", &token)]);
    app.send(Method::POST, &query_only, None, None)
        .await
        .assert_error(StatusCode::UNAUTHORIZED, "UNAUTHORIZED");
    app.send(Method::POST, split, Some(&token), None)
        .await
        .assert_error(StatusCode::NOT_FOUND, "NOT_FOUND");

    app.shutdown().await;
}

/// The log stream delivers decodable events to a session or a full key, and
/// closes once its key is downgraded to read-only.
#[tokio::test]
async fn log_stream_delivers_log_events_until_its_key_is_downgraded_to_read_only() {
    let app = TestApp::start().await;
    let token = app.admin_token().await;
    let key = app.create_api_key(&token, "sockets-full", "full").await;

    let mut session_socket = query_socket(&app, "/api/logging/stream", &token).await;
    let event = info_event(&app, &mut session_socket, &token).await;
    assert!(!event.target.is_empty(), "{event:?}");
    assert!(!event.message.is_empty(), "{event:?}");
    let age = now_ms() - event.timestamp_ms;
    assert!((0..60_000).contains(&age), "event is {age} ms old");

    let mut socket = query_socket(&app, "/api/logging/stream", &key.raw).await;
    info_event(&app, &mut socket, &token).await;

    // No API changes a key's access level; the row is edited directly. The
    // socket rechecks its credential every 5 s, so the close arrives within
    // about 5 s, leaving about 5 s of WAIT's 10 s as margin.
    app.run_sql(&format!(
        "UPDATE api_keys SET access_level = 'read_only' WHERE id = '{}'",
        key.id
    ))
    .await;

    assert_closes(&mut socket).await;
    app.refused_socket("/api/logging/stream", Some(&key.raw))
        .await
        .assert_error(StatusCode::FORBIDDEN, "API_KEY_READ_ONLY");

    app.shutdown().await;
}

/// A downloads socket sends a full snapshot on connect and on every
/// subscription change, and closes once its API key is revoked or its session
/// logs out. Each socket is checked after its own credential change, so a
/// change that closed every socket could not pass for the other.
#[tokio::test]
async fn downloads_socket_snapshots_every_subscription_change_until_its_credential_dies() {
    let app = TestApp::start().await;
    let session = app.admin().await.clone();

    // An upload in progress belongs to a streamer other than the one the
    // socket narrows to below.
    let started_at_ms = now_ms() - 1_000;
    app.run_sql(&format!(
        r#"INSERT INTO job (id, job_type, status, config, state, created_at, updated_at, input,
             streamer_id, session_id, started_at)
           VALUES ('upload-job', 'rclone', 'PROCESSING', '{{}}',
             '{{"streamer_name": "Uploading Streamer"}}', {started_at_ms}, {started_at_ms},
             '["/recordings/part-1.flv", "/recordings/part-2.flv"]', 'uploading-streamer',
             'upload-session', {started_at_ms})"#
    ))
    .await;

    let session_path = with_query("/api/downloads/ws", &[("token", &session.access)]);
    let mut session_socket = app.connect_socket(&session_path, None).await;

    let first = download_progress::WsMessage::decode(next_binary(&mut session_socket).await)
        .expect("decode the first frame");
    assert_eq!(
        first.event_type,
        download_progress::EventType::Snapshot as i32
    );
    let Some(download_progress::ws_message::Payload::Snapshot(snapshot)) = first.payload else {
        panic!("the first frame is not a snapshot");
    };
    let assert_upload_listed = |snapshot: &download_progress::DownloadSnapshot| {
        assert!(snapshot.downloads.is_empty());
        assert!(snapshot.queued.is_empty());
        assert_eq!(snapshot.uploads.len(), 1, "{snapshot:?}");
        let upload = snapshot.uploads[0]
            .started
            .as_ref()
            .expect("upload start state");
        assert_eq!(upload.job_id, "upload-job");
        assert_eq!(upload.streamer_id, "uploading-streamer");
        assert_eq!(upload.streamer_name, "Uploading Streamer");
        assert_eq!(upload.session_id, "upload-session");
        assert_eq!(upload.uploader, "rclone");
        assert_eq!(upload.files_total, 2);
        assert_eq!(upload.started_at_ms, started_at_ms);
    };
    assert_upload_listed(&snapshot);

    // The client replaces its stores from every snapshot, so narrowing to
    // one streamer must still carry every streamer's uploads.
    subscribe(&mut session_socket, Some("watched-streamer")).await;
    assert_upload_listed(&next_snapshot(&mut session_socket).await);
    subscribe(&mut session_socket, None).await;
    assert_upload_listed(&next_snapshot(&mut session_socket).await);

    let key = app
        .create_api_key(&session.access, "sockets-full", "full")
        .await;
    let mut key_socket = app
        .connect_socket("/api/downloads/ws", Some(&key.raw))
        .await;
    assert_upload_listed(&next_snapshot(&mut key_socket).await);

    app.delete(&format!("/api/auth/api-keys/{}", key.id), &session.access)
        .await
        .expect_status(StatusCode::OK);
    assert_closes(&mut key_socket).await;
    app.refused_socket("/api/downloads/ws", Some(&key.raw))
        .await
        .assert_error(StatusCode::UNAUTHORIZED, "UNAUTHORIZED");

    app.post(
        "/api/auth/logout",
        &session.access,
        &json!({ "refresh_token": session.refresh }),
    )
    .await
    .expect_status(StatusCode::OK);
    assert_closes(&mut session_socket).await;
    app.refused_socket(&session_path, None)
        .await
        .assert_error(StatusCode::UNAUTHORIZED, "UNAUTHORIZED");

    app.shutdown().await;
}

/// The next frame on the downloads socket whose payload `select` picks;
/// other frames are skipped.
async fn next_payload<T>(
    socket: &mut Socket,
    what: &str,
    mut select: impl FnMut(download_progress::ws_message::Payload) -> Option<T>,
) -> T {
    tokio::time::timeout(WAIT, async {
        loop {
            let message = download_progress::WsMessage::decode(next_binary(socket).await)
                .expect("decode a downloads frame");
            if let Some(selected) = message.payload.and_then(&mut select) {
                return selected;
            }
        }
    })
    .await
    .unwrap_or_else(|_| panic!("timed out waiting for {what}"))
}

#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn downloads_socket_streams_meta_progress_and_segment_frames_for_a_live_recording() {
    use download_progress::ws_message::Payload;

    let fake = FakePlatform::start().await;
    let room = fake.room("socket");
    let app = TestApp::start_with(Seed::live()).await;
    let token = app.admin_token().await;
    let mut socket = query_socket(&app, "/api/downloads/ws", &token).await;
    next_snapshot(&mut socket).await;
    // The room is offline until the socket narrows to the streamer.
    let id = id_of(
        &app.create_enabled_streamer(&token, json!({ "name": "Socket", "url": room.url() }))
            .await,
    );
    subscribe(&mut socket, Some(&id)).await;
    next_snapshot(&mut socket).await;
    room.set_live(room.live("Socket show"));

    // The live check's row and the download's start are announced by
    // different tasks, so their frames can arrive in either order.
    let (mut check, mut meta) = (None, None);
    tokio::time::timeout(WAIT, async {
        while check.is_none() || meta.is_none() {
            let what = "the live check and the download meta";
            next_payload(&mut socket, what, |payload| {
                match payload {
                    Payload::StreamerCheckRecorded(found) if found.outcome == "live" => {
                        check = Some(found);
                    }
                    Payload::DownloadMeta(found) => _ = meta.get_or_insert(found),
                    _ => return None,
                }
                Some(())
            })
            .await;
        }
    })
    .await
    .expect("timed out waiting for the live check and the download meta");
    let (check, meta) = (
        check.expect("the live check"),
        meta.expect("the download meta"),
    );
    assert_eq!(check.streamer_id, id);
    assert_eq!(check.title, "Socket show");
    assert_eq!(check.streams_extracted, 1);
    let selected: serde_json::Value =
        serde_json::from_str(&check.stream_selected_json).expect("selected stream JSON");
    assert_eq!(
        selected,
        json!({
            "bitrate": 16_000, "codec": "", "fps": 0.0,
            "media_format": "Flv", "quality": "origin", "stream_format": "Flv",
        })
    );

    assert_eq!(meta.streamer_id, id);
    assert_eq!(meta.engine_type, "mesio");
    assert_eq!(meta.download_url, room.flv_url());
    assert_eq!(
        meta.cdn_host,
        url::Url::parse(&room.flv_url())
            .expect("the room's FLV URL")
            .authority()
    );
    assert_recent(meta.started_at_ms);

    // Progress is reported about once a second while media arrives, so the
    // room keeps sending until the first report.
    room.wait_for_media_connection(1).await;
    let mut flv = FlvLoop::tiny();
    room.push(flv.stream(1));
    let metrics = tokio::time::timeout(WAIT, async {
        loop {
            let progress =
                next_payload(&mut socket, "download progress", |payload| match payload {
                    Payload::DownloadMetrics(metrics) if metrics.bytes_downloaded > 0 => {
                        Some(metrics)
                    }
                    _ => None,
                });
            match tokio::time::timeout(Duration::from_millis(250), progress).await {
                Ok(metrics) => return metrics,
                Err(_) => room.push(flv.next_loop()),
            }
        }
    })
    .await
    .expect("timed out waiting for download progress");
    assert_eq!(metrics.download_id, meta.download_id);
    assert_eq!(metrics.status, "downloading");
    assert_eq!(metrics.segments_completed, 0);
    room.set_offline();
    room.end();

    let segment = next_payload(&mut socket, "the segment", |payload| match payload {
        Payload::SegmentCompleted(segment) => Some(segment),
        _ => None,
    })
    .await;
    let completed = next_payload(&mut socket, "the download's end", |payload| match payload {
        Payload::DownloadCompleted(completed) => Some(completed),
        _ => None,
    })
    .await;

    // The frames describe the recording the REST API reports.
    let session_id = meta.session_id.clone();
    let segments_path = format!("/api/sessions/{session_id}/segments");
    let recorded = eventually(WAIT, "the segment to be stored", || async {
        let segments = app
            .get(&segments_path, &token)
            .await
            .expect_status(StatusCode::OK)
            .body;
        let first = &segments["items"][0];
        (!first.is_null()).then(|| first.clone())
    })
    .await;
    assert_eq!(
        (
            segment.download_id.as_str(),
            segment.streamer_id.as_str(),
            segment.session_id.as_str(),
            segment.segment_index,
            segment.split_reason.as_str(),
        ),
        (
            meta.download_id.as_str(),
            id.as_str(),
            session_id.as_str(),
            0,
            ""
        )
    );
    assert_eq!(
        Some(segment.segment_path.as_str()),
        recorded["file_path"].as_str()
    );
    assert_eq!(Some(segment.size_bytes), recorded["size_bytes"].as_u64());
    assert_eq!(
        Some(segment.duration_secs),
        recorded["duration_secs"].as_f64()
    );
    assert!(
        meta.started_at_ms <= segment.started_at_ms
            && segment.started_at_ms <= segment.completed_at_ms,
        "{segment:?}"
    );
    assert_eq!(
        (
            completed.download_id.as_str(),
            completed.session_id.as_str(),
            completed.total_bytes,
            completed.total_duration_secs,
            completed.total_segments,
        ),
        (
            meta.download_id.as_str(),
            session_id.as_str(),
            segment.size_bytes,
            segment.duration_secs,
            1
        )
    );

    app.shutdown().await;
}

/// With every slot taken (one normal, plus two only high-priority downloads
/// may use), live streamers wait on the queue. A connecting client's
/// snapshot lists each with its session, engine and priority tier, so the
/// queued badge survives a reconnect.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn downloads_snapshot_lists_queued_recordings_with_their_session_and_priority() {
    let fake = FakePlatform::start().await;
    let app = TestApp::start_with(Seed::live().global("max_concurrent_downloads", 1)).await;
    let token = app.admin_token().await;
    let watch = async |name: &str, priority: &str| {
        let room = fake.room(name);
        room.set_live(room.live(name));
        let created = app
            .create_enabled_streamer(
                &token,
                json!({ "name": name, "url": room.url(), "priority": priority }),
            )
            .await;
        (room, id_of(&created))
    };
    for name in ["first", "second", "third"] {
        let (room, _) = watch(name, "HIGH").await;
        room.wait_for_media_connection(1).await;
    }
    let (_, high) = watch("waiting-high", "HIGH").await;
    let (_, normal) = watch("waiting-normal", "NORMAL").await;

    let mut socket = query_socket(&app, "/api/downloads/ws", &token).await;
    let mut snapshot = next_snapshot(&mut socket).await;
    // Each subscription change sends a fresh snapshot.
    let deadline = tokio::time::Instant::now() + WAIT;
    while snapshot.queued.len() < 2 {
        assert!(
            tokio::time::Instant::now() < deadline,
            "both streamers queued: {snapshot:?}"
        );
        subscribe(&mut socket, None).await;
        snapshot = next_snapshot(&mut socket).await;
    }
    assert_eq!(snapshot.downloads.len(), 3, "{snapshot:?}");
    for (id, is_high_priority) in [(&high, true), (&normal, false)] {
        let queued = snapshot
            .queued
            .iter()
            .find(|queued| &queued.streamer_id == id)
            .unwrap_or_else(|| panic!("{id} is not queued: {snapshot:?}"));
        let sessions = app
            .get(&format!("/api/sessions?streamer_id={id}"), &token)
            .await
            .expect_status(StatusCode::OK)
            .body;
        assert_eq!(queued.session_id, sessions["items"][0]["id"], "{id}");
        assert_eq!(queued.engine_type, "mesio");
        assert_eq!(queued.is_high_priority, is_high_priority, "{id}");
        assert_recent(queued.queued_at_ms);
    }

    app.shutdown().await;
}
